/**
 * Builds supabase/seed.sql from the TypeScript catalogs, so the app and the
 * database never disagree about fields, skills, synonyms, or schools.
 *
 * The sample listings are for LOCAL DEVELOPMENT ONLY. The Supabase CLI runs
 * seed.sql on `supabase db reset` (local), never on `db push` to a hosted
 * project. Real listings come from admin import (Phase 6) and JSearch (Phase 5).
 */
import { FIELDS } from "@/lib/catalog/fields";
import { ALL_RESOURCES } from "@/lib/catalog/resources";
import { SCHOOLS } from "@/lib/catalog/schools";
import { SKILLS, SYNONYM_GROUPS } from "@/lib/catalog/skills";
import { dedupeKey } from "@/lib/listings/dedupe";
import { SAMPLE_LISTINGS, isClosed } from "@/lib/sample/listings";

/** A safe SQL string literal: single quotes doubled, no other escapes needed in standard_conforming_strings. */
export function lit(value: string | null): string {
  return value === null ? "null" : `'${value.replace(/'/g, "''")}'`;
}

function arr(values: readonly string[]): string {
  return values.length ? `array[${values.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
}

const num = (n: number | null) => (n === null ? "null" : String(n));

export function buildSeedSql(): string {
  const out: string[] = [
    "-- GENERATED by `npm run db:seed` from src/lib/catalog and src/lib/sample. Do not edit by hand.",
    "-- Reference data is safe anywhere. The internships below are FICTIONAL samples for local",
    "-- development only (the Supabase CLI runs this file on `db reset`, not on `db push`).",
    "",
    "begin;",
    "",
    "insert into public.fields (id, label, short_label, sort) values",
    FIELDS.map((f, i) => `  (${lit(f.id)}, ${lit(f.label)}, ${lit(f.short)}, ${i + 1})`).join(",\n") + "\non conflict (id) do update set label = excluded.label, short_label = excluded.short_label, sort = excluded.sort;",
    "",
    "insert into public.skills (id, name, field_ids, aliases) values",
    SKILLS.map((s) => `  (${lit(s.id)}, ${lit(s.name)}, ${arr(s.fields)}, ${arr(s.aliases ?? [])})`).join(",\n") +
      "\non conflict (id) do update set name = excluded.name, field_ids = excluded.field_ids, aliases = excluded.aliases;",
    "",
  ];

  // The first id in each synonym group is the canonical one.
  const synonyms = SYNONYM_GROUPS.flatMap((group) => group.slice(1).map((id) => [id, group[0]] as const));
  if (synonyms.length) {
    out.push(
      "insert into public.skill_synonyms (skill_id, canonical_id) values",
      synonyms.map(([s, c]) => `  (${lit(s)}, ${lit(c)})`).join(",\n") + "\non conflict (skill_id) do update set canonical_id = excluded.canonical_id;",
      "",
    );
  }

  out.push(
    "insert into public.schools (id, name) values",
    SCHOOLS.map((s) => `  (${lit(s.id)}, ${lit(s.name)})`).join(",\n") + "\non conflict (id) do update set name = excluded.name;",
    "",
    // Learning resources for missing skills (src/lib/catalog/resources.ts). Needs migration 0006.
    "insert into public.skill_resources (id, skill_id, title, url, type, sort) values",
    ALL_RESOURCES.map(
      (r) => `  (${lit(r.id)}, ${lit(r.skillId)}, ${lit(r.title)}, ${lit(r.url)}, ${lit(r.type)}, ${Number(r.id.split("-").pop())})`,
    ).join(",\n") +
      "\non conflict (id) do update set skill_id = excluded.skill_id, title = excluded.title, url = excluded.url, type = excluded.type, sort = excluded.sort;",
    "",
    "-- ---- Sample listings (local development only) ----",
    "",
  );

  for (const l of SAMPLE_LISTINGS) {
    out.push(
      "insert into public.internships (id, title, company_name, verified, source, field_id, area, lat, lng, work_type, allowance, hours, moa, deadline, posted_at, snippet, apply_kind, apply_url, apply_email, is_active, dedupe_key) values (",
      `  ${lit(l.id)}, ${lit(l.title)}, ${lit(l.company)}, ${l.verified}, ${lit(l.source)}, ${lit(l.field)}, ${lit(l.area)},`,
      `  ${num(l.location?.lat ?? null)}, ${num(l.location?.lng ?? null)}, ${lit(l.workType)}, ${lit(l.allowance)}, ${num(l.hours)}, ${l.moa},`,
      `  ${l.deadlineInDays === null ? "null" : `current_date + ${l.deadlineInDays}`}, now() - interval '${l.postedDaysAgo} days',`,
      `  ${lit(l.snippet)},`,
      `  ${lit(l.apply.kind)}, ${lit(l.apply.kind === "link" ? l.apply.url : null)}, ${lit(l.apply.kind === "email" ? l.apply.email : null)},`,
      `  ${!isClosed(l)}, ${lit(dedupeKey(l.company, l.title, l.area))}`,
      ") on conflict (id) do nothing;",
    );
    out.push(
      "insert into public.internship_skills (internship_id, skill_id, required) values",
      l.skills.map((s) => `  (${lit(l.id)}, ${lit(s.id)}, ${s.required})`).join(",\n") + "\non conflict do nothing;",
      "",
    );
  }

  out.push("commit;", "");
  return out.join("\n");
}
